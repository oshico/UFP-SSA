# Churn prediction & CLV optimisation in e-commerce (SSA - MEINF / UFP).
# Pipeline: load -> clean -> FX API -> RFM + churn label -> EDA -> logistic regression.

# 1. Packages ------------------------------------------------------------------
suppressPackageStartupMessages({
  library(tidyverse) # dplyr, ggplot2, readr, stringr
  library(lubridate) # date and time handling
  library(httr2)     # REST requests
  library(jsonlite)  # JSON parsing
})

# 2. Paths ---------------------------------------------------------------------
# Relative only, so the analysis runs from a clean checkout at the project root.
data_dir <- file.path("data", "raw")
out_dir  <- file.path("data", "processed")
fig_dir  <- file.path("docs", "figures")

for (d in c(data_dir, out_dir, fig_dir)) {
  dir.create(d, showWarnings = FALSE, recursive = TRUE)
}

dataset_path <- file.path(data_dir, "data.csv")
if (!file.exists(dataset_path)) {
  stop(
    "Dataset not found at ", dataset_path, "\n",
    "Run data/raw/download_data.R to fetch it from the UCI repository."
  )
}

cat("=== 1. Loading the transactional data ===\n")
cat("File:", dataset_path, "\n")

# 3. Reading -------------------------------------------------------------------
# Column types are pinned instead of guessed: readr would otherwise infer the
# date and CustomerID inconsistently across rows with missing values.
df_raw <- read_csv(
  dataset_path,
  col_types = cols(
    InvoiceNo   = col_character(),
    StockCode   = col_character(),
    Description = col_character(),
    Quantity    = col_integer(),
    InvoiceDate = col_character(),
    UnitPrice   = col_double(),
    CustomerID  = col_character(), # identifier, not a measure: keep it as text
    Country     = col_character()
  )
)

# Formats are tried in order. "m/d/Y H:M" is the format UCI ships; ISO first
# covers files regenerated by download_data.R. Ambiguity here silently shifts
# every date by months, which would corrupt Recency and therefore the label.
DATE_ORDERS <- c("Y-m-d H:M", "m/d/Y H:M", "d/m/Y H:M")

cat(
  "Raw dimensions:", format(nrow(df_raw), big.mark = ","), "rows x",
  ncol(df_raw), "columns.\n"
)

# 4. Cleaning ------------------------------------------------------------------
cat("=== 2. Cleaning and formatting ===\n")

df_clean <- df_raw %>%
  mutate(InvoiceDate = parse_date_time(InvoiceDate, orders = DATE_ORDERS)) %>%
  # A return is either an invoice prefixed with "C" or a negative quantity.
  mutate(Is_Return = str_detect(InvoiceNo, "^C") | Quantity < 0) %>%
  # Rows without a customer cannot be scored, and non-positive prices are
  # accounting artefacts rather than sales.
  filter(
    !is.na(CustomerID),
    UnitPrice > 0
  ) %>%
  mutate(LineTotal_GBP = Quantity * UnitPrice)

cat("Rows after dropping missing customers and invalid prices:",
    format(nrow(df_clean), big.mark = ","), "\n")

# 5. Currency normalisation ----------------------------------------------------
cat("=== 3. Fetching the GBP -> EUR rate from the REST API ===\n")

#' Look up a GBP -> EUR exchange rate.
#'
#' Queries `api_url` when one is supplied, otherwise returns the hardcoded
#' fallback. A failed request never aborts the pipeline: falling back keeps the
#' run reproducible when the network is unavailable or rate limited.
get_gbp_to_eur_rate <- function(base_curr = "GBP", target_curr = "EUR", api_url = NULL) {
  fallback_rate <- 1.17 # 1 GBP = 1.17 EUR

  if (is.null(api_url)) {
    cat(sprintf("Offline mode: using the fallback rate 1 GBP = %s EUR\n", fallback_rate))
    return(fallback_rate)
  }

  tryCatch(
    {
      rate <- resp_body_json(request(api_url) %>% req_perform())[[target_curr]]
      cat(sprintf("Rate from API (%s -> %s): %s\n", base_curr, target_curr, rate))
      rate
    },
    error = function(e) {
      cat(sprintf(
        "API unavailable (%s); using the fallback rate %s\n",
        conditionMessage(e), fallback_rate
      ))
      fallback_rate
    }
  )
}

gbp_to_eur <- get_gbp_to_eur_rate("GBP", "EUR")

df_clean <- df_clean %>%
  mutate(LineTotal_EUR = LineTotal_GBP * gbp_to_eur)

# 6. RFM features and churn label ----------------------------------------------
cat("=== 4. Feature engineering: building the RFM matrix ===\n")

# The reference date is one day after the last transaction, so a recency of 0
# days means "purchased on the final day of the window".
max_date <- max(df_clean$InvoiceDate, na.rm = TRUE) + days(1)
cat("Reference date:", format(max_date, "%Y-%m-%d"), "\n")

rfm_df <- df_clean %>%
  group_by(CustomerID) %>%
  summarise(
    LastPurchaseDate = max(InvoiceDate, na.rm = TRUE),
    Recency_Days     = as.numeric(difftime(max_date, LastPurchaseDate, units = "days")),

    # Returns are excluded from the purchase counts so they cannot inflate them.
    Frequency_Orders   = n_distinct(InvoiceNo[!Is_Return]),
    Monetary_Total     = sum(LineTotal_EUR[!Is_Return], na.rm = TRUE),
    Total_Transactions = n(),
    Return_Transactions = sum(Is_Return),
    Return_Ratio        = Return_Transactions / Total_Transactions,
    Country = first(Country),
    .groups = "drop"
  ) %>%
  # Customers with no net spend have nothing to model.
  filter(Monetary_Total > 0) %>%
  mutate(
    # Target: no purchase for more than 90 days before the reference date.
    Churn_90d = factor(
      if_else(Recency_Days > 90, 1, 0),
      levels = c(0, 1), labels = c("Active", "Churn")
    ),
    # log1p tames the long right tail of spend while still handling zero.
    Log_Monetary = log1p(Monetary_Total)
  )

cat("Unique customers analysed:", format(nrow(rfm_df), big.mark = ","), "\n")
cat("Churn label distribution:\n")
print(table(rfm_df$Churn_90d))

processed_path <- file.path(out_dir, "customer_rfm_churn_processed.csv")
write_csv(rfm_df, processed_path)
cat("Processed dataset written to:", processed_path, "\n")

# 7. Exploratory analysis ------------------------------------------------------
cat("=== 5. Generating the exploratory figures ===\n")

STATE_COLOURS <- c("Active" = "#1B9E77", "Churn" = "#D95F02")

p1 <- ggplot(rfm_df, aes(x = Churn_90d, y = Log_Monetary, fill = Churn_90d)) +
  geom_boxplot(alpha = 0.7, outlier.color = "red", outlier.shape = 1) +
  scale_fill_manual(values = STATE_COLOURS) +
  theme_minimal() +
  labs(
    title = "Monetary value (log) by churn status",
    subtitle = "Active customers vs. customers inactive for more than 90 days",
    x = "Customer status (90-day churn)",
    y = "Log(1 + monetary value in EUR)",
    fill = "Status"
  ) +
  theme(plot.title = element_text(face = "bold", size = 12))

ggsave(file.path(fig_dir, "eda_boxplot_churn_monetary.png"), plot = p1, width = 7, height = 5)

p2 <- ggplot(rfm_df, aes(x = Recency_Days, y = Frequency_Orders, color = Churn_90d)) +
  geom_point(alpha = 0.6, size = 2) +
  scale_color_manual(values = STATE_COLOURS) +
  scale_y_log10() +
  theme_minimal() +
  labs(
    title = "Order frequency vs. recency in days",
    subtitle = "Logarithmic scale on order frequency",
    x = "Recency (days since last purchase)",
    y = "Frequency (number of orders)",
    color = "Status"
  ) +
  theme(plot.title = element_text(face = "bold", size = 12))

ggsave(file.path(fig_dir, "eda_scatter_frequency_recency.png"), plot = p2, width = 7, height = 5)

cat("Figures written to", fig_dir, "\n")

# 8. Predictive modelling ------------------------------------------------------
cat("=== 6. Training the logistic regression churn model ===\n")

#' Confusion matrix and classification metrics for a binary outcome.
#'
#' Replaces caret::confusionMatrix: the whole caret stack is a heavy dependency
#' for what is a count-and-divide calculation. `truth` and `pred` must be
#' factors sharing the same levels, where the first level counts as negative.
confusion_metrics <- function(truth, pred, positive = "Churn") {
  stopifnot(identical(levels(truth), levels(pred)), nchar(positive) > 0)

  tp <- sum(pred == positive & truth == positive)
  tn <- sum(pred != positive & truth != positive)
  fp <- sum(pred == positive & truth != positive)
  fn <- sum(pred != positive & truth == positive)

  # A zero denominator means the metric is undefined; NA is more honest than NaN.
  div <- function(num, den) if (den == 0) NA_real_ else num / den

  matrix_tbl <- table(Predicted = pred, Actual = truth)

  list(
    matrix = matrix_tbl,
    accuracy   = div(tp + tn, tp + tn + fp + fn),
    sensitivity = div(tp, tp + fn),
    specificity = div(tn, tn + fp),
    precision   = div(tp, tp + fp),
    f1          = div(2 * tp, 2 * tp + fp + fn)
  )
}

set.seed(123)
# Stratified 70/30 split, so the class balance carries into both subsets.
# Rows are sampled within each churn class rather than globally.
train_index <- unlist(
  lapply(
    split(seq_len(nrow(rfm_df)), rfm_df$Churn_90d),
    function(idx) sample(idx, floor(0.70 * length(idx)))
  ),
  use.names = FALSE
)
train_set <- rfm_df[train_index, ]
test_set  <- rfm_df[-train_index, ]

cat(sprintf("Train: %s rows | Test: %s rows\n",
            format(nrow(train_set), big.mark = ","),
            format(nrow(test_set), big.mark = ",")))

model_logit <- glm(
  Churn_90d ~ Frequency_Orders + Log_Monetary + Return_Ratio,
  data = train_set,
  family = binomial(link = "logit")
)

cat("\n--- Logistic regression summary ---\n")
print(summary(model_logit))

test_preds_prob <- predict(model_logit, newdata = test_set, type = "response")
test_preds_class <- factor(
  if_else(test_preds_prob > 0.5, "Churn", "Active"),
  levels = c("Active", "Churn")
)

cat("\n--- Confusion matrix (test set) ---\n")
metrics <- confusion_metrics(test_set$Churn_90d, test_preds_class, positive = "Churn")
print(metrics$matrix)
cat(sprintf(
  "\nAccuracy: %.3f | Sensitivity: %.3f | Specificity: %.3f | Precision: %.3f | F1: %.3f\n",
  metrics$accuracy, metrics$sensitivity, metrics$specificity,
  metrics$precision, metrics$f1
))

cat("\n=== Script finished successfully ===\n")