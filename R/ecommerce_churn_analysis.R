  Return_Ratio + Tenure_30d + Is_UK

model_logit <- glm(model_formula, data = train_set, family = binomial(link = "logit"))

# Decision tree: grown with a small cp, then pruned back to the complexity with
# the lowest 10-fold cross-validated error.
