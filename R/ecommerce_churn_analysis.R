build_rfm <- function(tx, ref) {
  tx %>%
    group_by(CustomerID) %>%
    summarise(
      # Purchases only: a recent return is not activity.
      Last_Purchase    = suppressWarnings(max(InvoiceDate[!Is_Return & !Is_Cancelled_Purchase])),
      First_Purchase   = suppressWarnings(min(InvoiceDate[!Is_Return & !Is_Cancelled_Purchase])),
      Frequency_Orders = n_distinct(InvoiceNo[!Is_Return & !Is_Cancelled_Purchase]),
      Monetary_EUR     = sum(LineTotal_EUR[!Is_Return & !Is_Cancelled_Purchase]),
      Total_Lines      = n(),
      Return_Lines     = sum(Is_Return),
      Country          = first(Country),
      .groups = "drop"
    ) %>%
    # Customers whose only activity was returns or cancelled orders bought nothing.
    filter(Frequency_Orders > 0, Monetary_EUR > 0) %>%
    mutate(
      Recency_Days  = as.numeric(difftime(ref, Last_Purchase, units = "days")),
      Tenure_Days   = as.numeric(difftime(ref, First_Purchase, units = "days")),
      Return_Ratio  = Return_Lines / Total_Lines,
      AOV_EUR       = Monetary_EUR / Frequency_Orders,
      # log1p tames the long right tail of spend and frequency (see M3).
      Log_Monetary  = log1p(Monetary_EUR),
      Log_Frequency = log1p(Frequency_Orders),
      Is_UK         = as.integer(Country == "United Kingdom")
    )
}

