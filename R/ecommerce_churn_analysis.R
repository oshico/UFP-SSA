## ---- churn-frame ----
# P4: predict churn within 90 days.
#
# The label must not be built from the same window as the features. Otherwise
# "churner" means "no purchase in the last 90 days", a churner has had less time
# to place orders, and the model partly learns that by construction (this was
# open issue 3). So: features use only transactions BEFORE a cutoff; the label
# looks at the 90 days AFTER it. Recency can then be a predictor without leakage.
# Cancellations are re-matched on the past alone: a return made after the
# cutoff must not change the features.
build_churn_frame <- function(tx, cutoff, window = CHURN_WINDOW_DAYS) {
  past   <- tx %>% filter(InvoiceDate < cutoff) %>% flag_cancellations()
  future <- tx %>%
    filter(InvoiceDate >= cutoff, InvoiceDate < cutoff + days(window),
           !Is_Return, !Is_Cancelled_Purchase) %>%
    distinct(CustomerID) %>%
    mutate(Bought_After = TRUE)

  build_rfm(past, cutoff) %>%
    left_join(future, by = "CustomerID") %>%
    mutate(Churn_90d = factor(if_else(is.na(Bought_After), "Churn", "Ativo"),
                              levels = c("Ativo", "Churn")),
           # Per-30-day units so the odds ratios are readable (per day is ~1).
           Recency_30d = Recency_Days / 30,
           Tenure_30d  = Tenure_Days / 30) %>%
    select(-Bought_After)
}

