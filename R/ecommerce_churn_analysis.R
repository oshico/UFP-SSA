## ---- fx ----
# Daily GBP -> EUR reference rates (ECB, via the Frankfurter REST API) for the
# whole period. Each transaction is converted at the rate of its own day, which
# is more faithful than one present-day rate applied to 2010-11 sales.
#
# Historical rates never change, so the API answer is cached in data/external/
# (gitignored; a fresh clone fetches it again): later runs are deterministic
# and work offline. If there is no
# cache and the API fails, a single fallback rate keeps the pipeline running.
FX_CACHE         <- file.path(ext_dir, "fx_gbp_eur_daily.csv")
FX_FALLBACK_RATE <- 1.15 # approx. ECB 2011 annual average (EUR/GBP 0.868)

get_fx_rates <- function(start, end, cache = FX_CACHE,
                         api_url = "https://api.frankfurter.app") {
  if (file.exists(cache)) {
    rates <- read_csv(cache, col_types = cols(Date = col_date(), GBP_EUR = col_double()))
    return(list(rates = rates, source = "cache"))
  }
  tryCatch(
    {
      body <- request(api_url) %>%
        req_url_path_append(paste0(start, "..", end)) %>%
        req_url_query(from = "GBP", to = "EUR") %>%
        req_timeout(20) %>%
        req_perform() %>%
        resp_body_json()
      rates <- tibble(
        Date    = as_date(names(body$rates)),
        GBP_EUR = map_dbl(body$rates, "EUR")
      )
      if (nrow(rates) == 0) stop("empty response")
      write_csv(rates, cache)
      list(rates = rates, source = "api")
    },
    error = function(e) {
      log_step("FX API unavailable (", conditionMessage(e), "); using fallback ",
               FX_FALLBACK_RATE)
      list(rates = tibble(Date = as_date(start), GBP_EUR = FX_FALLBACK_RATE),
           source = "fallback")
    }
  )
}

