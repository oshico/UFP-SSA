# Outlier treatment. The extreme quantities in this file (e.g. 80,995 and
# 74,215 units) are orders cancelled in full minutes later. Rather than drop
# rows above an arbitrary threshold, every purchase line that was later
# returned in full (same customer, product and quantity, at any time after the
# purchase) is flagged, so it does not count as spend. Matching is one-to-one.
# Partial returns are not matched: they only count towards the return ratio.
# A function, because the churn frame re-runs it on pre-cutoff data only.
flag_cancellations <- function(tx) {
  purchases <- tx %>%
    filter(!Is_Return) %>%
    transmute(Line_ID, CustomerID, StockCode, Qty = Quantity, P_Date = InvoiceDate)
  returns <- tx %>%
    filter(Is_Return) %>%
    transmute(CustomerID, StockCode, Qty = -Quantity, R_Date = InvoiceDate)

  cancelled_ids <- purchases %>%
    arrange(P_Date) %>%
    group_by(CustomerID, StockCode, Qty) %>% mutate(k = row_number()) %>% ungroup() %>%
    inner_join(
      returns %>% arrange(R_Date) %>%
        group_by(CustomerID, StockCode, Qty) %>% mutate(k = row_number()) %>% ungroup(),
      by = c("CustomerID", "StockCode", "Qty", "k")
    ) %>%
    filter(R_Date >= P_Date) %>%
    pull(Line_ID)

  mutate(tx, Is_Cancelled_Purchase = Line_ID %in% cancelled_ids)
}

