## ---- model-helpers ----
#' Confusion matrix and classification metrics for a binary outcome.
#' Base R instead of caret: it is a count-and-divide calculation.
confusion_metrics <- function(truth, pred, positive = "Churn") {
  stopifnot(identical(levels(truth), levels(pred)))
  tp <- sum(pred == positive & truth == positive)
  tn <- sum(pred != positive & truth != positive)
  fp <- sum(pred == positive & truth != positive)
  fn <- sum(pred != positive & truth == positive)
  div <- function(num, den) if (den == 0) NA_real_ else num / den
  list(
    matrix      = table(Previsto = pred, Real = truth),
    accuracy    = div(tp + tn, tp + tn + fp + fn),
    sensitivity = div(tp, tp + fn),
    specificity = div(tn, tn + fp),
    precision   = div(tp, tp + fp),
    f1          = div(2 * tp, 2 * tp + fp + fn)
  )
}

#' ROC curve points and AUC. AUC uses the Mann-Whitney identity: the
#' probability that a random churner scores higher than a random active customer.
roc_auc <- function(truth, score, positive = "Churn") {
  y  <- as.integer(truth == positive)
  n1 <- sum(y); n0 <- length(y) - n1
  auc <- (sum(rank(score)[y == 1]) - n1 * (n1 + 1) / 2) / (n1 * n0)
  o <- order(score, decreasing = TRUE)
  curve <- tibble(score = score[o], y = y[o]) %>%
    mutate(tpr = cumsum(y) / n1, fpr = cumsum(1 - y) / n0) %>%
    group_by(score) %>% slice_tail(n = 1) %>% ungroup() %>%
    arrange(fpr, tpr)
  list(auc = auc, curve = bind_rows(tibble(fpr = 0, tpr = 0), select(curve, fpr, tpr)))
}

classify <- function(prob, threshold) {
  factor(if_else(prob >= threshold, "Churn", "Ativo"), levels = c("Ativo", "Churn"))
}

